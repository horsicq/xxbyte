/*
 * Container listing (xxbyte_disasm_file, "xxbyte_cli -f vb -F"): a compiled
 * Visual Basic 5/6 PE32 i386 image (EXE, DLL or OCX). The VB header
 * ("VB5!", EXEPROJECTINFO) is found through the entry point's
 * "push offset VBHeader; call ThunRTMain", else as the first "VB5!" whose
 * ProjectInfo (version 0x1F4) and object table lie in the file. The listing
 * walks ProjectInfo -> object table -> public object descriptors ->
 * ObjectInfo, and lists every P-code procedure of every object: the
 * descriptors (xxbyte_vb_proc_desc) in ObjectInfo's method table whose
 * object_info points back at that ObjectInfo, in method order, each code
 * body cut at xxbyte_vb_proc_code_size (the whole proc_size when that
 * fails). Lines:
 *   ; Visual Basic 6 P-code project "Project1": VB header 0x00401048, 2 objects
 *   ; object "Form1": type 0x18083, ObjectInfo 0x004013A0, 3 methods (3 P-code), 9 constants
 *   ; procedure Form1.Command1_Click: RTMI 0x00401600, code 0x004015D8, 0x26 bytes + 0x2 filler, frame 0x5C
 * then the procedure's listing with addresses relative to its first P-code
 * byte (the space branch targets use). A native-code project (ProjectInfo
 * lpNativeCode set) lists its objects and "; native code: no P-code
 * procedures". XXBYTE_MODE_AUTO decodes MSVBVM50 opcodes when the image
 * imports MSVBVM50.DLL and not MSVBVM60.DLL, else MSVBVM60 opcodes.
 *
 * Procedure names: Object.Control_Event for event handlers, from the
 * optional object info's control list (controls, their GUIDs and event
 * tables, whose entries are stubs that load the descriptor), with event
 * names from MSVBVM60's own class table in event-sink slot order for the
 * intrinsic controls (Form, CommandButton, TextBox, Timer, Menu, ...; slot 6
 * of a Form is Load) and Event<slot> for other controls or a count that does
 * not match; Object.Name for methods with a name in the public object
 * descriptor's name table; Object.Proc_<method index> otherwise.
 *
 * The listing's resolver names constant-pool operands (INDEX CONSTANT and
 * INDEX IMPORT, list entries included) by what the pool entry points at:
 *   jmp [IAT] stub        DLL!Name, MSVBVM60.DLL ordinals by their export
 *                         names ("MSVBVM60.DLL!rtcMsgBox"), others "DLL!#595"
 *   Declare stub          lib!function from its DeclareInfo
 *                         ("kernel32!GetTickCount")
 *   P-code call stub      the procedure's name ("Module1.DoWork")
 *   GUID                  "{33AD4ED9-6699-11CF-B70C-00AA0060D393}" for VCall*
 *                         interfaces and New* classes
 *   string                for mnemonics with "Str" or "Late" (LitStr,
 *                         LitVarStr, LateMem*): a BSTR literal or a
 *                         NUL-terminated UTF-16 member name, quoted with C
 *                         escapes (\", \\, \r, \n, \t, \xNN, \uNNNN) and cut
 *                         at 120 characters; a null pool entry is ""
 * and keeps the numeric form otherwise (global variable slots of ImpAdLd*
 * and ImpAdSt*, record descriptors, entries outside the pool).
 * Limitations: VB5's MSVBVM50 class table and ordinal names are not
 * included (no intact MSVBVM50.DLL was available), so VB5 ordinals print as
 * numbers and VB5 event names use the VB6 table; ActiveX controls' events
 * are Event<slot>; class modules' Class_Initialize/Class_Terminate and
 * other unnamed private procedures are Proc_<n>.
 */

