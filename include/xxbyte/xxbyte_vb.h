/*
 * Visual Basic 5 and 6 share one P-code encoding, executed by MSVBVM50.DLL
 * and MSVBVM60.DLL. Opcodes 00 to FA take one byte; the lead bytes FB to FF
 * select five more tables and the opcode is lead << 8 | second byte
 * (FB01 ImpUI1). XXBYTE_VB_MODE_DEFAULT and XXBYTE_VB_MODE_VB6 decode the
 * MSVBVM60 opcode set; XXBYTE_VB_MODE_VB5 decodes the MSVBVM50 set, which
 * lacks the 20 opcodes VB6 added (FF03, FF04, FF32 to FF3E and FF41 to
 * FF45), and reads the Redim element type as MSVBVM50 does (see below).
 * MSVBVM50's FE1D VCallCbFrame handler skips the vtable offset that
 * MSVBVM60 reads and calls through the misaligned vtable offset 1D, so
 * working VB5 programs are unlikely to contain it; VB5 mode decodes FE1D
 * as the 4 bytes that runtime consumes, the opcode and the return-flags
 * word ("VCallCbFrame 0x4"), where VB6 decodes 6 bytes
 * ("VCallCbFrame vt_02F8, 0x4").
 */
#define XXBYTE_VB_MODE_DEFAULT 0u
#define XXBYTE_VB_MODE_VB5 5u
#define XXBYTE_VB_MODE_VB6 6u

/*
 * Operands and text. Branch operands (Branch, BranchF, For*, Next*,
 * OnErrorGoto, Resume, Gosub, OnGoto, ...) hold an offset from the start
 * of the procedure's P-code, and the BRANCH value is that offset: pass the
 * instruction's offset within the procedure as the decode address so
 * addresses and targets share one space. Operands print as
 *   frame offsets     INDEX FRAME, signed: "var_8C" (negative, locals) and
 *                     "arg_8" (positive, arguments)
 *   constant pool     INDEX CONSTANT "const_0012"
 *   import slots      INDEX IMPORT "imp_0012" (ImpAd*: the constant-pool
 *                     slot that holds an import or global address)
 *   vtable offsets    INDEX VTABLE "vt_02F8" (VCall*, ThisVCall*)
 *   branch targets    BRANCH "loc_0034"; OnErrorGoto 0, FFFE and FFFF and
 *                     Resume FFFE and FFFF are IMMEDIATE "0xFFFF"
 *                     (OnErrorGoto FFFE = On Error GoTo 0, FFFF = On Error
 *                     Resume Next, 0 clears the active error and keeps the
 *                     handler; Resume FFFE retries the failed statement,
 *                     FFFF = Resume Next)
 *   literals          signed decimal (LitI2 -1, LitI4 100000), floating
 *                     point as FLOAT (LitR4FP, LitR8, LitDate), currency
 *                     (LitCy, LitCy4, LitVarCy) as the raw 64-bit value
 *                     divided by 10000 ("1.5")
 *   other immediates  unsigned hex "0x8" (stack byte counts, argument
 *                     counts, member offsets, DISPIDs, LargeBos statement
 *                     lengths); signed member offsets "-0x8"
 * Redim and RedimPreserve take the dimension count, the element type, the
 * element size and the FADF flags: "Redim 0x1, 0x11, 0x1, 0x80". The
 * element type is an IMMEDIATE VARTYPE ("0x11", VT_UI1) when the flags
 * have FADF_HAVEVARTYPE (0x80), which MSVBVM50 ignores, or when it is FFFF
 * (none); otherwise it is the INDEX CONSTANT of an IRecordInfo or IID
 * ("const_0005").
 * Variable-length forms (FFreeAd, FFreeStr, FFreeVar, OnGoto, OnGosub,
 * GetRecOwner3/4, PutRecOwner3/4, LateMemNamed*, LateIdNamed*) start with a
 * 16-bit byte count. Their fixed fields are operands and the list that
 * follows is an inline table (table_count, table_offset) read with
 * xxbyte_vb_list_entry: "FFreeVar var_8C, var_90", "OnGoto loc_0010,
 * loc_0020", "LateIdNamedCall 0x60030000, 0x2, {0x1, 0x2}". OnGoto and
 * OnGosub are switches whose entry i has key i + 1. The formatter passes
 * each INDEX or BRANCH list entry to the resolver as the only operand
 * (operand_index 0) of a copy of the instruction.
 */

